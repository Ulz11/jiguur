import { test, expect } from '../../fixtures';
import { expectReady } from '../../support/routes';

/**
 * УДИРДЛАГЫН ТӨВ — ТООНУУД ӨӨРСДИЙГӨӨ ТАЙЛБАРЛАНА.
 *
 * Гурван чимээгүй худал энд амьдарч байв:
 *   1. «90+ хоног хэтэрсэн» гэсэн шошгын доор `d.aging[3]` гэсэн ИНДЕКСЭЭР
 *      уншсан тоо зогсдог байв. Сервер «Хугацаа болоогүй» гэсэн шинэ хувинг
 *      ЭХЭНД нэмэхэд тэр индекс «61–90» руу гулсаж, шошго нь ОГТ ӨӨР тоог
 *      нэрлэж эхэлсэн — алдаа дуугардаггүй, зөвхөн худал хариулдаг.
 *   2. «12 нэхэмжлэл хэтэрсэн» гэдэг тоо нь ХЭДЭН ХҮН гэдгийг хэлдэггүй —
 *      атал залгах ажил нь ХҮНЭЭР хэмжигдэнэ.
 *   3. Дугуйлсан «77.4 сая₮» нь бүтэн дүнгээ ЗӨВХӨН `title`-д нуудаг байв —
 *      Отгоо хулгана хөвүүлдэггүй, планшет дээр огт боломжгүй.
 */
test.describe('удирдлагын төвийн тоонууд', () => {
  /* ⚠ ДӨРВӨН баталгаа НЭГ хуудас ачаалалт дээр. Тусад нь дөрвөн тест
     болговол хуудас дөрөв ачаалагдаж, ганц ажилчинтай тестийн сервер 546КБ
     багцыг дөрөв дамжуулна — тэр ачаалал өөрөө флейк төрүүлдэг
     (`fits-her-screen.spec.ts`-ийн ижил тайлбар). Алдааны мессеж бүр АЛЬ
     шалгалт унасныг өөрөө нэрлэнэ. */
  test('насжилт, хэтэрсэн карт, бүтэн ₮, графикийн гарчиг — бүгд өөрсдийгөө хэлнэ',
    async ({ managerPage }) => {
      /* Дата ҮҮСГЭХГҮЙ: seed-д хугацаа хэтэрсэн нэхэмжлэл, идэвхтэй гэрээ
         аль хэдийн бий. Шалгаж байгаа зүйл нь ХЭЛБЭР, тоо биш. */
      await managerPage.goto('/');
      await expectReady(managerPage, 'Удирдлагын төв', '/');

      /* ---- 1. НАСЖИЛТ: ХҮЛЭЭЛТ ба ХОЦРОЛТ ---- */
      const card = managerPage.locator('.card').filter({
        has: managerPage.getByRole('heading', { name: 'Авлага насжилтаар' }) }).first();
      /* Хугацаа нь болоогүй нэхэмжлэл «0–30 хоног» хувинд суудаг байв:
         маргааш төлөгдөх мөнгө «хоцорсон» гэж уншигдана. */
      for (const label of ['Хугацаа болоогүй', '0–30 хоног', '31–60', '61–90', '90+']) {
        await expect(card.getByText(label, { exact: true }), `«${label}» хувин алга`)
          .toBeVisible();
      }

      /* Хөлийн мөрийн «90+» нь ТҮЛХҮҮРЭЭРЭЭ олдоно: хувингийн мөрийнхтэй
         ЯГ ижил тоо байх ёстой. Индексээр («aging[3]») уншсан бол «61–90»-
         ийнх гарах байв. Картын текстийг МӨР МӨРӨӨР нь уншина — «яг …₮»
         гэсэн бүтэн дүн нь шошгынхоо дараа зогсоно. */
      const lines = (await card.innerText()).split('\n').map((l) => l.trim());
      /** Шошгын ДАРААХ эхний тоо — «47.0 сая» / «47.0 сая₮» / «0» бүгд НЭГ
       *  дүн (₮ тэмдэг, зай нь байрлалаас хамаарна). */
      const numAfter = (label: string) => {
        const i = lines.indexOf(label);
        expect(i, `«${label}» мөр насжилтын картад алга`).toBeGreaterThan(-1);
        const hit = lines.slice(i + 1, i + 4).find((l) => /\d/.test(l) && !l.startsWith('яг '));
        expect(hit, `«${label}» дээр дүн зурагдсангүй`).toBeTruthy();
        return hit!.replace(/[₮\s]/g, '');
      };
      expect(numAfter('90+ хоног хэтэрсэн'),
             '«90+ хоног хэтэрсэн» хөлийн мөр өөр хувингийн тоог зурж байна')
        .toBe(numAfter('90+'));

      /* Дугуйлагдсан дүн бүрийн доор БҮТЭН тоо ил зогсоно (дугуйлагдаагүй
         жижиг тоон дээр тэр мөр гарахгүй — «яг 213₮» юу ч нэмэхгүй). */
      expect(lines.some((l) => /^яг [\d,]+₮$/.test(l)),
             'насжилтын картад нэг ч бүтэн дүн ил гарсангүй').toBe(true);

      /* Хувингуудын нийлбэр нь авлагын НИЙТ дүнтэй тэнцдэггүй — тэр зөрүү
         тайлбаргүй бол «энэ график буруу» гэж уншигдана. */
      const foot = lines.find((l) => l.startsWith('нэхэмжилсэн '));
      if (foot) {
        expect(foot, 'хөлийн тайлбар нийлбэрээ бүтнээр хэлсэнгүй')
          .toMatch(/^нэхэмжилсэн [\d,]+₮ \+ нэхэмжлэгдээгүй [\d,]+₮ = [\d,]+₮$/);
      }

      /* ---- 2. «Хугацаа хэтэрсэн» карт: ХЭДЭН ХҮН ---- */
      const tile = managerPage.locator('.command-metric').filter({
        hasText: 'Хугацаа хэтэрсэн' }).first();
      await expect(tile.getByText(/\d+ нэхэмжлэл · \d+ харилцагч/),
                   'хэтэрсэн карт нь ХЭДЭН ХҮН гэдгийг хэлсэнгүй').toBeVisible();

      /* ---- 3. Дугуйлсан тооны БҮТЭН дүн ИЛ (title дотор нуугдахгүй) ---- */
      await expect(managerPage.locator('.command-hero').first().getByText(/^яг [\d,]+₮$/),
                   'авлагын бүтэн дүн зөвхөн title дотор нуугдлаа').toBeVisible();
      await expect(tile.getByText(/^яг [\d,]+₮$/),
                   'хэтэрсэн дүнгийн бүтэн тоо ил биш').toBeVisible();

      /* ---- 4. График нь ЮУНААС бодогдсоноо нэрлэнэ ----
         «Орлого» гэдэг үг нь Тайлангийн «Түрээсийн орлого»-той нэг зүйл мэт
         уншигддаг байв — үнэндээ тэр нь НЭХЭМЖИЛСЭН дүн, энэ нь ОРСОН МӨНГӨ. */
      await expect(managerPage.getByRole('heading',
                     { name: 'Орсон мөнгө — Түрээс · Худалдаа · Бартер (төлбөрөөр)' }),
                   'графикийн гарчиг эх сурвалжаа нэрлэсэнгүй').toBeVisible();

      /* ---- 5. Циклийн шошго ISO огноогоор ----
         «3.15 – 4.13» гэсэн цэгтэй хэлбэр нь «15-р сарын 3 уу?» гэсэн
         эргэлзээ төрүүлдэг — хажуугийн нүд бүр ISO байхад ганц энэ нь өөр. */
      const table = managerPage.locator('.card').filter({
        has: managerPage.getByRole('heading', { name: 'Хүлээгдэж буй төлбөр' }) }).first();
      const row = table.locator('tbody tr').first();
      await expect(row, 'хүлээгдэж буй төлбөрийн хүснэгт хоосон байна').toBeVisible();
      const cell = await row.getByRole('cell').first().innerText();
      expect(cell, `циклийн шошго ISO болоогүй: «${cell}»`)
        .toMatch(/\d{4}-\d{2}-\d{2} – \d{4}-\d{2}-\d{2}/);
    });
});
