import { test, expect } from '../../fixtures';
import { expectReady } from '../../support/routes';

/**
 * МЭДЭГДЛИЙГ ТҮР НУУХ — «АЛГА БОЛГОХ» БИШ, «ХОЙШЛУУЛАХ».
 *
 * «Батбаяр ХХК — R-26/07 12 хоног хэтэрлээ» гэсэн мөр өдөр бүр гарч ирнэ.
 * Отгоо тэр хүнтэй ярьж «сарын 15-нд төлнө» гэж тохирсон бол тэр мөр долоо
 * хоног хэрэггүй — атал жагсаалтаас гарах арга байхгүй тул түүний доорх
 * БОДИТ ШИНЭ мэдэгдэл нүднээс гардаг байв (жагсаалт 20 мөрөөр таслагддаг).
 *
 * Нуулт нь ЭРГЭЖ БОЛНО: «5 нуугдсан · харах» нь юуг нуусныг нэрлэж,
 * буцаах товчтойгоо зогсоно.
 */
test('мэдэгдлийг 7 хоног нууж, буцааж болно', async ({ managerPage }) => {
  /* ⚠ Энэ тест ДАТА ҮҮСГЭХГҮЙ: самбар дээр мэдэгдэл нь seed-ээс (хугацаа
     хэтэрсэн нэхэмжлэл, зээлийн төлөлт) аль хэдийн төрдөг. Гүйлт бүрд шинэ
     гэрээ нэмбэл тестийн DB өсөж, `/api/dashboard` гэрээ БҮРИЙГ алхдаг тул
     огт хамаагүй тестүүд цаг хэтрэлтээр унана. Асуулт нь «АЛЬ Ч мөрийг
     нууж, буцааж чадах уу» гэдэг тул тодорхой харилцагч шаардлагагүй. */
  await managerPage.goto('/');
  await expectReady(managerPage, 'Удирдлагын төв', '/');

  const card = managerPage.locator('.card').filter({
    has: managerPage.getByRole('heading', { name: 'Мэдэгдэл' }) }).first();

  /* Товчны нэр нь ХЭДЭН хоног болохыг ӨӨРӨӨ хэлнэ — «түр» гэдэг үг дангаараа
     «хэдий хүртэл?» гэсэн асуулт үлдээнэ. */
  /* Дуудагдах нэр нь ЯМАР мөрийг нуухыг хэлдэг («{гарчиг} — 7 хоног түр
     нуух»): жагсаалтад 20 ижил нэртэй товч зэрэгцвэл уншигчаар ажилладаг
     хүн аль нь алийг нь нуухыг мэдэхгүй. */
  const hide = card.getByRole('button', { name: /— 7 хоног түр нуух$/ }).first();
  await expect(hide, '«Түр нуух» товч мөрөн дээр алга').toBeVisible();
  /* ХАРАГДАХ бичиг нь ХЭДЭН хоног болохыг хэлнэ — «түр» дангаараа
     «хэдий хүртэл?» гэсэн асуулт үлдээнэ. */
  await expect(hide, 'товчны бичиг хоногоо хэлсэнгүй').toHaveText(/Түр нуух \(7 хоног\)/);
  const box = (await hide.boundingBox())!;
  expect(Math.round(box.height), '«Түр нуух» 36px-ийн шатанд хүрэхгүй')
    .toBeGreaterThanOrEqual(36);

  /* ⚠ Жагсаалт 20 мөрөөр таслагддаг тул нуусны дараа ТООЛУУР нь буурахгүй
     (21 дэх мөр орж ирнэ) — баталгаа нь ЯГ ТЭР мөрөөр явна. */
  const label = (await hide.getAttribute('aria-label'))!;
  const title = label.replace(/ — 7 хоног түр нуух$/, '');
  const hidden = card.getByRole('button', { name: label, exact: true });

  await hide.click();

  /* 1. ЯГ ТЭР мөр жагсаалтаас гарна */
  await expect(hidden, 'нуусан мөр жагсаалтад үлдлээ').toHaveCount(0);

  /* 2. Нуугдсан гэдгээ картын толгой ХЭЛНЭ — «алга болсон» гэж уншигдахгүй */
  const show = card.getByRole('button', { name: /нуугдсан · харах/ });
  await expect(show, 'нуугдсан мөрийн тоо картын толгой дээр алга').toBeVisible();

  /* 3. «харах» нь ЮУГ нуусныг НЭРЛЭЖ, БУЦААХ товчтой */
  await show.click();
  await expect(card.getByText(title, { exact: false }).first(),
               'нуугдсан мөр нэрээрээ жагсаагдсангүй').toBeVisible();
  const back = card.getByRole('button', { name: 'Буцаах' }).first();
  await expect(back, '«Буцаах» товч алга — нуулт нь устгалтай адил боллоо')
    .toBeVisible();
  await back.click();

  /* 4. Буцаасны дараа ЯГ ТЭР мөр ЖАГСААЛТАД эргэж ирнэ */
  await expect(hidden, 'нуулт цуцлагдсан ч мөр эргэж ирсэнгүй').toHaveCount(1);
});
