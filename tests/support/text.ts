/**
 * Шошгыг ЯГ таарах, гэхдээ ТОМ/жижиг үсгээс хамааралгүй хэв болгоно.
 *
 * ЯАГААД: хуудасны олон шошго CSS-ийн `uppercase`-ээр ТОМООР зурагддаг
 * («Нийт үлдэгдэл» → «НИЙТ ҮЛДЭГДЭЛ»), эх кодод нь жижгээр бичигдсэн байдаг.
 * Хоёрын аль нэгийг нь сонговол тест кодын хэв маягаас хамаарна — шошго нь
 * ижил хэвээр байхад CSS ангийг сольсноор тест унана.
 */
export function exactLabel(label: string): RegExp {
  return new RegExp(`^${label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}$`, 'i');
}
