import { describe, it, expect } from "vitest";
import { agreedMark, agreedTitle, clientInvoiceLabel, invoiceLabel, isAgreed,
         isEntryNo } from "./invoice";

// Нэг нэхэмжлэлийг хоёр өөр нэрээр дуудвал Отгоо тэднийг хоёр өөр объект гэж
// уншина. Тиймээс нэр нь НЭГ дүрмээс гарна: түрээсийнх — үе, бусад нь — №.

describe("invoiceLabel", () => {
  /* ШОШГЫН ФОРМАТ (M5/R4): цонх нь [7.20, 8.19) хэвээр ирдэг, НЭР нь
     БАГТААМЖТАЙ гарна — «7.20 – 8.18» = 30 хоног. Урьд нь 31 хоног мэт
     уншигдаж, Отгоо «машин нэг хоног нэмчихлээ» гэж дүгнэдэг байв. */
  it("түрээсийн нэхэмжлэлийг үеээр нь нэрлэж, дугаарыг хоёрдогч болгоно", () => {
    expect(invoiceLabel({ no: "R-24/03-4", cycle_start: "2026-07-20", cycle_end: "2026-08-19" }))
      .toEqual({ title: "2026-07-20 – 2026-08-18", sub: "№R-24/03-4" });
  });

  it("худалдааны нэхэмжлэлд үе байхгүй (цикл = нэг өдөр) тул № нь өөрөө нэр", () => {
    expect(invoiceLabel({ no: "S-26/15-3", cycle_start: "2026-05-04", cycle_end: "2026-05-04" }))
      .toEqual({ title: "№S-26/15-3" });
  });

  /* ЧАНГАРУУЛСАН (2026-09): урьд нь «№OB-5» гэж гардаг байсныг СОЛИВ.
     Отгоо «№OB-5» гэсэн баримт хэзээ ч гаргаж байгаагүй — тэр мөрийг
     хараад «энэ ямар нэхэмжлэл вэ» гэж эргэлзэнэ. Одоо дугаар нь ОГТ
     гарахгүй: үг нь, хамрах огноотойгоо гарна. */
  it("хуучин үлдэгдлийн (OB) нэхэмжлэл нь дугааргүй, ҮГЭЭРЭЭ нэрлэгдэнэ", () => {
    expect(invoiceLabel({ no: "OB-5", cycle_start: "2026-01-01", cycle_end: "2026-01-01" }))
      .toEqual({ title: "Хуучин үлдэгдэл", sub: "2026-01-01 хүртэл" });
  });

  it("хуучин үлдэгдэлд огноо ирээгүй бол «— хүртэл» гэсэн хий мөр гарахгүй", () => {
    expect(invoiceLabel({ no: "OB-5" })).toEqual({ title: "Хуучин үлдэгдэл" });
  });

  it("үеийн огноо алга бол № рүү унана", () => {
    expect(invoiceLabel({ no: "R-9" })).toEqual({ title: "№R-9" });
  });
});

/* ХАРИЛЦАГЧИЙН ХУУДАС — нэг жагсаалт дотор гурван гэрээ, хуучин үлдэгдэл,
   гараар бичсэн бичилт зэрэгцэн сууна. Мөр бүр ЮУНЫХ болохоо өөрөө хэлнэ. */
describe("clientInvoiceLabel", () => {
  it("хуучин үлдэгдлийг ҮГЭЭР нь, хамрах огноотой нь нэрлэнэ", () => {
    expect(clientInvoiceLabel({ no: "OB-4", cycle_start: "2026-09-01",
                                cycle_end: "2026-09-01" }))
      .toEqual({ title: "Хуучин үлдэгдэл", sub: "2026-09-01 хүртэл" });
  });

  /* ГОЛ ЗАСВАР: `A-…` нь ХУУЧИН ҮЛДЭГДЛИЙН зохиомол гэрээн дээр суудаг.
     Гэрээгээр нь таньдаг байсан тул Бутангуудын «Өнө Ордтой тооцоо»
     139,648,000₮ нь «Хуучин үлдэгдэл · 2026-09-01 хүртэл» гэж нэрлэгдэж байв. */
  it("гараар бичсэн бичилтийг өөрийнх нь шошгоор нэрлэнэ (хуучин үлдэгдэл БИШ)", () => {
    expect(clientInvoiceLabel({ no: "A-4-1", cycle_start: "2026-06-22",
                                cycle_end: "2026-06-22",
                                label: "Өнө Ордтой тооцоо — 2026.06.22 акт" }))
      .toEqual({ title: "Өнө Ордтой тооцоо — 2026.06.22 акт", sub: "2026-06-22" });
  });

  it("шошгогүй бичилт хоосон гарчиг зурахгүй", () => {
    expect(clientInvoiceLabel({ no: "A-4-2", label: "" })).toEqual({ title: "Бичилт" });
  });

  it("түрээсийн нэхэмжлэл ЮУ болохоо хэлж, хилээ БАГТААМЖТАЙ зурна", () => {
    expect(clientInvoiceLabel({ no: "25.19-4", cycle_start: "2026-07-13",
                                cycle_end: "2026-08-12" }))
      .toEqual({ title: "Түрээс 2026-07-13 – 2026-08-11" });
  });

  it("худалдааны нэхэмжлэлд үе байхгүй тул № нь өөрөө нэр", () => {
    expect(clientInvoiceLabel({ no: "S-3", cycle_start: "2026-05-04",
                                cycle_end: "2026-05-04" }))
      .toEqual({ title: "№S-3" });
  });

  it("isEntryNo нь ЗӨВХӨН `A-{харилцагч}-{n}` хэлбэрийг таньна", () => {
    expect(isEntryNo("A-4-1")).toBe(true);
    expect(isEntryNo("OB-4")).toBe(false);
    expect(isEntryNo("A-мөр")).toBe(false);
    expect(isEntryNo(null)).toBe(false);
  });
});

describe("«Тооцоо нийлсэн» тэмдэг", () => {
  it("огноо ба гарын үсэгтний нэрийг НЭГ өгүүлбэр болгоно", () => {
    expect(agreedMark({ agreed_at: "2026-07-20", agreed_by: "Н.Манлай" }))
      .toBe("Тооцоо нийлсэн 2026-07-20 · Н.Манлай");
  });

  it("гарын үсэгтэн бичигдээгүй бол огноо ганцаараа зогсоно", () => {
    expect(agreedMark({ agreed_at: "2026-07-20", agreed_by: "" }))
      .toBe("Тооцоо нийлсэн 2026-07-20");
  });

  it("тэмдэглэгээгүй нэхэмжлэл ХООСОН — хий шошго нэмэхгүй", () => {
    expect(agreedMark({ agreed_at: null, agreed_by: "" })).toBe("");
    expect(agreedMark(undefined)).toBe("");
    expect(isAgreed({ agreed_at: null })).toBe(false);
    expect(isAgreed({ agreed_at: "2026-07-20" })).toBe(true);
  });

  it("tooltip нь зөвхөн батлагдсан мөрөнд гарна", () => {
    expect(agreedTitle({ agreed_at: null })).toBeUndefined();
    expect(agreedTitle({ agreed_at: "2026-07-20", agreed_by: "Н.Манлай" }))
      .toBe("Тооцоо нийлсэн 2026-07-20 · Н.Манлай");
  });
});
