/* ИЛҮҮ ТӨЛӨЛТ — МӨНГӨ БАЙГАА АТЛАА ДЭЛГЭЦ ДЭЭР БАЙХГҮЙ БАЙВ.
 *
 * Хурд групп 78,165,000₮ илүү төлсөн: тэр мөнгө системд БАЙНА (хуваарилагдаагүй
 * төлбөр), дараагийн нэхэмжлэл гармагц өөрөө сууна. Гэвч харилцагчийн хуудас
 * «Авлага 0₮ · Хэвийн» гэж зогсдог байв — Отгоо эгчийн нүдэнд тэр харилцагч
 * ТЭГТЭЙ, өртэй ч биш, өгөх ч юмгүй. Илүү төлөлт нь зөвхөн «Төлбөр» табын
 * нэг мөр болж нуугдана.
 *
 * Энэ нь ЖИНХЭНЭ мөнгөний асуудал: тэр харилцагч руу «төлбөрөө хийгээрэй»
 * гэж залгаж болно, эсвэл 78 саяыг мартаж болно. Хоёул алдаа.
 *
 * ДҮРЭМ: авлага нь тэг байхад кредит нь тэгээс их бол ТӨЛӨВ өөрөө өөрчлөгдөнө
 * («Кредиттэй»), тоон нүдэнд нь БҮТЭН дүнтэй дэд мөр гарна. Өнгө дангаараа
 * утга зөөхгүй — үг нь пилийн дотор өөрөө зогсоно (UI-ЗАРЧИМ §4).
 *
 * Цэвэр логик (React-гүй, сүлжээгүй): дэлгэц нь зөвхөн зурна.
 */

/** Дугуйлалтын шуугиан: 1₮-ийн кредит мөр болох ёсгүй. */
const MIN_SHOW = 0.5;

export type PaymentCredit = {
  amount: number;
  /** Нэхэмжлэлүүдэд СУУСАН хэсэг (`serializers.payment`). */
  allocated?: number | null;
  voided?: boolean;
};

/** ХУВААРИЛАГДААГҮЙ КРЕДИТ — амьд төлбөр бүрийн үлдэгдлийн нийлбэр.
 *
 *  Хүчингүй болсон төлбөр ОРОХГҮЙ: тэр мөнгө буцаж гарсан (мөр нь түүхэнд
 *  үлдсэн ч тооцоонд байхгүй). `allocated` ирээгүй бол БҮГД суусан гэж үзнэ —
 *  хуучин сервертэй ярихад хий кредит зохиохоос. */
export function unallocatedCredit(payments: PaymentCredit[] | null | undefined): number {
  let sum = 0;
  for (const p of payments || []) {
    if (p.voided) continue;
    const left = (p.amount || 0) - (p.allocated ?? p.amount ?? 0);
    if (left > 0) sum += left;
  }
  return sum;
}

/** Кредитийн дэд мөр. Гаргах зүйлгүй бол ХООСОН (мөр нь огт гарахгүй).
 *
 *  Тоо нь БҮТЭН төгрөгөөр: энэ бол «дараа нь юу болох вэ» гэсэн ажлын дүн,
 *  дугуйлсан «78.2 сая» нь тулгахад хүрэлцэхгүй. */
export function creditLine(credit: number, fmtMoney: (v: number) => string): string {
  if (!(credit > MIN_SHOW)) return "";
  return `Илүү төлөлт (кредит): ${fmtMoney(credit)} — дараагийн нэхэмжлэлээс хасагдана`;
}

export type ClientState = { cls: string; label: string };

/** ХАРИЛЦАГЧИЙН ТӨЛӨВ — толгойн пил.
 *
 *  Дараалал нь ЯАРАЛТАЙН дарааллаар: хэтэрсэн өр → үлдэгдэл → кредит →
 *  хэвийн. Кредит нь «хэвийн»-ээс ӨӨР төлөв: тэр харилцагчид БИД өртэй. */
export function clientState(receivable: number, overdue: boolean,
                            credit = 0): ClientState {
  if (overdue) return { cls: "pill-red", label: "Хэтэрсэн өртэй" };
  if (receivable > 0) return { cls: "pill-amber", label: "Үлдэгдэлтэй" };
  /* Мөнгөний өнгө (`pill-green` = `bg-money-50 text-money`) — «Хэвийн»-тэй
     ижил шат. Ялгааг нь ӨНГӨ биш ҮГ зөөнө (UI-ЗАРЧИМ §4). */
  if (credit > MIN_SHOW) return { cls: "pill-green", label: "Кредиттэй" };
  return { cls: "pill-green", label: "Хэвийн" };
}

/** ДУГУЙЛСАН ба БҮТЭН тоо ИЖИЛ байвал хоёр дахь мөр гарахгүй.
 *
 *  Тэг авлагатай харилцагч дээр «0₮» гэсэн мөр ХОЁР удаа дараалж зогсдог
 *  байв — эхнийх нь дугуйлсан (`sayaFmt`), хоёр дахь нь бүтэн (`money`).
 *  Хоёр ижил тоо нь мэдээлэл нэмэхгүй, зөвхөн «энэ хоёр яагаад өөр байгаа
 *  юм бол?» гэсэн асуулт үлдээнэ. */
export function exactBelow(headline: string, exact: string | undefined): string {
  return exact && exact !== headline ? exact : "";
}
