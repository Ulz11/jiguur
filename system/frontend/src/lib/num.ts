/* Хэрэглэгчийн ГАРААР бичсэн тоог (мөнгө, тариф, хувь, тоо ширхэг) тоо
 * болгон уншдаг ГАНЦ газар.
 *
 * Отгоо мөнгөө Excel-ээс хуулж тавьдаг: "6,000,000" эсвэл "6 000 000".
 * Энгийн `parseFloat("6,000,000")` нь эхний тасалахад зогсоод 6 болчихдог —
 * дүн ЧИМЭЭГҮЙ алдагддаг. Тиймээс мянгатын тусгаарлагчийг эхлээд арилгана.
 *
 * ДҮРЭМ (энэ системд):
 *   • таслал ба зай  = МЯНГАТЫН тусгаарлагч  →  "1,5" нь 1.5 биш, 15
 *   • цэг            = АРАВТЫН тусгаарлагч   →  "1.55" → 1.55, "0.5" → 0.5
 * Алдангийн хувь ("0.5"), тариф ("1.25") зэрэг бутархайг цэгээр бичнэ.
 */

/** Мянгатын тусгаарлагч болж болох бүх тэмдэгт: таслал, энгийн зай,
 *  хуулж тавихад ордог NBSP (U+00A0) ба нарийн NBSP (U+202F). */
const SEPARATORS = /[,\s  ]/g;

export function parseMoney(s: string | number | null | undefined): number {
  if (typeof s === "number") return Number.isFinite(s) ? s : 0;
  if (s === null || s === undefined) return 0;
  const n = parseFloat(String(s).replace(SEPARATORS, ""));
  return Number.isFinite(n) ? n : 0;
}

/** Бичиж байх үед мянгатыг бүлэглэнэ: "6000000" → "6,000,000".
 *  Хэрэглэгч бичиж дуусаагүй байхад нь саад болохгүй: "1234." → "1,234."
 *  Хоосныг 0 болгохгүй — placeholder нь харагдсаар байх ёстой. */
export function formatMoneyInput(s: string | number | null | undefined): string {
  if (s === null || s === undefined) return "";
  const raw = String(s).replace(SEPARATORS, "");
  if (raw === "") return "";
  const m = raw.match(/^(-?)(\d*)(\.\d*)?/);
  if (!m) return "";
  const [, sign, int = "", frac = ""] = m;
  if (!int && !frac) return "";
  const grouped = int.replace(/\B(?=(\d{3})+(?!\d))/g, ",");
  return sign + grouped + frac;
}

/* ---------- Тоо ХАРУУЛАХ (дээрх нь тоо УНШИХ) ---------- */

/** Мянгатыг бүлэглэсэн бүтэн тоо: 1234.6 → "1,235". */
export const fmt = (n: number) => Math.round(n).toLocaleString("en-US");

/* ШАТНЫ ХҮСНЭГТ — «сая»/«тэрбум»-ын ГАНЦ тодорхойлолт.
 *
 * `at`     — энэ шатанд шилжих босго;
 * `word`   — нэгжийн үг (угтвар зайтайгаа);
 * `digits` — тухайн шатны ЭНГИЙН нягтрал;
 * `max`    — дэд мөр ТЭГ болж дугуйлагдахаас хамгаалж нэмэгдэх оронгийн
 *            ДЭЭД хязгаар. Яг 1₮-ийн нарийвчлалд хүрээд зогсоно
 *            (сая → 6 орон = 1₮, тэрбум → 9 орон = 1₮), эс бөгөөс
 *            төгсгөлгүй бутархай төрнө.
 *
 * Тэрбум дээр ХОЁР орон (5.13) — нэг орон бол 100 сая тутам үсэрч,
 * «5.1 тэрбум» гэсэн тоо 50 саяын зөрүүг нууна. Сая дээр НЭГ орон хангалттай.
 */
const TIERS = [
  { at: 1_000_000_000, word: " тэрбум", digits: 2, max: 9 },
  { at: 1_000_000, word: " сая", digits: 1, max: 6 },
] as const;

/** Товч мөнгө — KPI карт, диаграмын шошго дээр бүтэн ₮ багтдаггүй.
 *
 * ГУРВАН ШАТ: бүтэн → сая → ТЭРБУМ. Тэрбумын шат байхгүй байхад компанийн
 * нийт өглөг «5,130 сая₮» гэж гарч байв — бизнес өөрөө «5.1 тэрбум» гэж
 * ярьдаг, төслийн баримт бичиг ч тэгж бичдэг. Хүн толгойдоо мянгад хувааж
 * байж уншдаг тоо нь богино байснаас ямар ч ашиггүй.
 *
 * ЯГ дүнг хаана ч алддаггүй: дуудагч талууд `title={money(n)}`-оор бүтнээр нь
 * барьдаг (hover дээр бүтэн ₮ гарна).
 */
export function sayaFmt(n: number): string {
  /* Тоо нь ӨӨРИЙНХӨӨ шатаар бичигдэнэ — өөрөө өөртэйгөө жишигдсэн хэлбэр. */
  return sayaFmtLike(n, n);
}

/** Тоог ӨӨР тооны ШАТААР бичнэ — нэг нүдэнд НЭГ хэмжүүр (H9b).
 *
 * ЯАГААД: «үүнээс нэхэмжлэгдээгүй», «+ алданги» зэрэг ДЭД мөрүүд толгой
 * мөрийнхөө ДООР зогсдог. Тэдгээрийг `sayaFmt`-аар бичвэл ӨӨРИЙНХӨӨ
 * хэмжээгээр шатладаг тул нэг нүдэнд хоёр өөр хэмжүүр дараалж болно:
 *
 *     1.2 сая₮
 *     үүнээс нэхэмжлэгдээгүй: 13,200₮        ← өөр хэмжүүр!
 *
 * Отгоо эгч нэг нүдийг НЭГ баримт гэж уншдаг: тэр хоёрыг хасах гэж оролдоод
 * утгагүй тоо гаргана, эсвэл (илүү аюултай нь) тоонд нь итгэхээ болино.
 * Бодит датад авлага нь зуун сая, циклийн хуримтлал нь мянгаар хэмжигддэг
 * тул энэ хос БАРАГ МӨР БҮР дээр гарна.
 *
 * ДҮРЭМ: дэд мөр нь ҮРГЭЛЖ ТОЛГОЙНХОО шатаар. Толгой «сая» бол дэд мөр ч
 * «сая» («0.01 сая₮» гэдэг нь бүрэн үнэн, зөвхөн богино); толгой бүтэн ₮ бол
 * дэд мөр ч бүтэн ₮. Хэзээ ч нэгжийн үгээ ХАЯХГҮЙ — хаях нь яг тэр хоёр
 * хэмжүүрийг буцааж авчирна.
 *
 * ЖИЖИГ ДҮНГИЙН НЯГТРАЛ (ганц дүрэм, хаа сайгүй): дэд мөр «0 сая₮» болж
 * дугуйлагдахаар бол ТЭГ БИШ болтол нь орон нэмнэ — 13,200₮ нь «0.0 сая»
 * биш «0.01 сая» гэж бичигдэнэ. Нэмэлт орон нь 1₮-ийн нарийвчлал дээр
 * зогсоно (`TIERS.max`).
 */
export function sayaFmtLike(n: number, reference: number): string {
  const tier = TIERS.find((t) => Math.abs(reference) >= t.at);
  if (!tier) return fmt(n);            // толгой нь бүтэн ₮ — дэд мөр ч бүтэн ₮
  const scaled = n / tier.at;
  /* «Тэг болж дугуйлагдах уу» — ГАРАЛТААР нь шалгана, оролтоор нь биш:
     0.0132 нь нэг оронтойд «0.0», хоёр оронтойд «0.01». */
  const roundsToZero = (d: number) => Math.round(Math.abs(scaled) * 10 ** d) === 0;
  let digits = tier.digits;
  while (digits < tier.max && roundsToZero(digits)) digits++;
  /* «-0 сая» гэж бичихгүй: дугуйлаад тэг болсон бол ТЭГ гэж бич. */
  const shown = roundsToZero(digits) ? 0 : scaled;
  return shown.toLocaleString("en-US", { maximumFractionDigits: digits }) + tier.word;
}
