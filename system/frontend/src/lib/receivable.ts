/* АВЛАГА — НЭГ ТОДОРХОЙЛОЛТ, БҮХ ДЭЛГЭЦЭД (Чадварын харьцуулалт H9b).
 *
 * Отгоо эгчид нэг харилцагчийн ХОЁР өөр нийт дүн ХЭЗЭЭ Ч харагдаж болохгүй.
 * Урьд нь дашбоард/харилцагчийн мөр нь «нэхэмжилсэн + одоогийн циклийн
 * хуримтлал», Авлага цуглуулах нь зөвхөн «нэхэмжилсэн» гэж хардаг байсан —
 * тэр хоёр дэлгэцийг зэрэгцүүлэн хараад «хуудсууд минь шиг л зөрж байна»
 * гэнэ. Шилжилтийн шалтгаан бүтнээрээ унана.
 *
 * ГАНЦ тодорхойлолт:  авлага = нэхэмжилсэн үлдэгдэл + одоогийн циклийн
 * хуримтлал. БҮРЭЛДЭХҮҮН нь харагдаж болно («үүнээс нэхэмжлэгдээгүй: X₮»),
 * НИЙТ дүн нь хаана ч ГАНЦ.
 *
 * Сервер (`billing.client_receivable` → `receivable_display`) аль хэдийн
 * дугуйлж, задаргааг НИЙТ дүн рүү нь нийлүүлж илгээдэг. Энд зөвхөн дэлгэцийн
 * дүрэм: хэзээ дэд мөр гаргах, ямар үгээр. React-гүй, сүлжээгүй, детерминистик.
 */
import { fmt, sayaFmtLike } from "./num";

/** Нэхэгдээгүй хуримтлалын ганц үг — бүх дэлгэц эндээс уншина. */
export const UNINVOICED = "нэхэмжлэгдээгүй";

/** Дугуйлалтын шуугиан: 1₮-ийн үлдэгдэл дэд мөр болох ёсгүй. */
const MIN_SHOW = 0.5;

export type ReceivableSplit = {
  /** Дэлгэц дээр гарах НИЙТ дүн — бүх хуудсанд ижил */
  total: number;
  /** Нэхэмжлэл болсон хэсэг */
  invoiced: number;
  /** Одоогийн цикл — хуримтлагдаж байгаа, хараахан нэхэгдээгүй */
  uninvoiced: number;
  /** Дэд мөр гаргах ёстой юу */
  showUninvoiced: boolean;
};

/** Серверийн `receivable` / `receivable_invoiced` (эсвэл `balance` /
 *  `balance_invoiced`) хоёрыг дэлгэцийн задаргаа болгоно. */
export function receivableSplit(total: number | undefined,
                                invoiced: number | undefined): ReceivableSplit {
  const t = Math.max(total || 0, 0);
  // Задаргаа НИЙТ дүнгээс давахгүй: сервер зөрүүтэй тоо илгээсэн ч дэлгэц
  // дээр сөрөг хэсэг гарахгүй — «−12,000₮ нэхэмжлэгдээгүй» гэдэг утгагүй.
  const inv = Math.min(Math.max(invoiced ?? t, 0), t);
  const un = Math.max(t - inv, 0);
  return { total: t, invoiced: inv, uninvoiced: un, showUninvoiced: un > MIN_SHOW };
}

/** Дэд мөрийн бичиг. Гаргах зүйлгүй бол ХООСОН мөр (мөр нь гарахгүй).
 *
 *  ҮГС нь дэлгэц бүр дээр ИЖИЛ; зөвхөн тооны нягтрал (бүтэн ₮ эсвэл «сая»)
 *  байрандаа тохирч өөрчлөгдөнө. Хоёр өөр үгтэй дэд мөр бол хоёр өөр ойлголт
 *  мэт уншигдана.
 *
 *  ХЭМЖҮҮРИЙГ ТОЛГОЙ нь ТОГТООНО, дэд мөр ӨӨРӨӨ БИШ. Урьд нь дуудагч тал
 *  форматч (`sayaFmt`) дамжуулдаг байсан нь дэд мөрийг ӨӨРИЙНХӨӨ хэмжээгээр
 *  шатлуулж, нэг нүдэнд хоёр хэмжүүр төрүүлдэг байв:
 *
 *      1.2 сая₮
 *      үүнээс нэхэмжлэгдээгүй: 13,200₮        ← толгойтойгоо өөр шат
 *
 *  Тиймээс одоо ФОРМАТЧ биш, ТОЛГОЙН ДҮН дамжина:
 *    · `sayaHeadline` өгсөн  → толгой нь `sayaFmt`-аар зурагддаг гэсэн үг;
 *      дэд мөр нь `sayaFmtLike`-аар ЯГ тэр шатанд бичигдэнэ («0.01 сая₮»).
 *    · `sayaHeadline` дутсан → толгой нь бүтэн ₮ (`money`); дэд мөр ч бүтэн ₮.
 *  Буруу форматч сонгох боломж БҮТЦЭЭРЭЭ үлдэхгүй.
 */
export function uninvoicedLine(uninvoiced: number, sayaHeadline?: number): string {
  if (uninvoiced <= MIN_SHOW) return "";
  const shown = sayaHeadline === undefined
    ? fmt(uninvoiced)
    : sayaFmtLike(uninvoiced, sayaHeadline);
  return `үүнээс ${UNINVOICED}: ${shown}₮`;
}

/** Хоёр дэлгэцийн тоог тулгах — зөрөх ёсгүй тул хатуу тэнцүү. */
export function sameReceivable(a: number, b: number): boolean {
  return a === b;
}
