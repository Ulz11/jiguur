/* Он цагийн хэлхээний бичиг — ДҮН нь ЯМАР ЯВДАЛ болсноос салгагдана.
 *
 * Харилцагчийн хуанли (`ClientProfile` → `TimelineCalendar`) нь серверээс
 * БЭЛЭН ӨГҮҮЛБЭР авдаг: «Төлбөр — 20,000,000₮», «Түрээс · барьцаа 500,000₮»,
 * «Ачилт — 40ш · №24/03». Энэ нь Отгоод зөв: тэр мөнгө, явдал хоёрыг нэг
 * мөрөнд уншина.
 *
 * Үйлдвэрийн даргад бол хуанли нь АЖЛЫН агуулга («энэ харилцагчид юу гарч,
 * юу буцав») — тэнд ₮ хутгалдвал эмх цэгц алдагдана (эзний шийдвэр 2026-09).
 * Хана биш: тоо нь хуудасны доод талын ХУМИГДСАН «Санхүү» задаргаанд бүтэн
 * зогсоно, зөвхөн ХЭЛХЭЭНЭЭС нь салгагдана.
 *
 * ⚠ Энэ нь СЕРВЕРИЙН бичгийг ЗАСАЖ байгаа тул үг нь өөрчлөгдвөл чимээгүй
 * алдаж магадгүй. Тиймээс хоёр давхар: (1) « · » хэсгүүдээс ₮-тэйг нь хасна,
 * (2) үлдсэн юманд ₮ дахин олдвол тоон хэсгийг нь ШУУД арчина. E2E
 * (`money-tidy.spec.ts`) нь даргын дэлгэц дээрх ₮ бүрийг тоолдог тул
 * энэ хоёрын аль нь ч ажиллахгүй бол тест УНАНА.
 */

/** Тоо + ₮ (мянгатын таслал, аравтын цэг, зайтай хэлбэрүүд). */
const AMOUNT = /-?\d[\d,.\s]*₮/g;

/** Хэлхээний нэг мөрөөс ДҮНГ салгана. Явдал нь үлдэнэ, тоо нь явна. */
export function withoutMoney(text: string | null | undefined): string {
  const raw = (text ?? "").trim();
  if (!raw.includes("₮")) return raw;

  const parts = raw.split(" · ").map((part) => {
    if (!part.includes("₮")) return part;
    /* Тоог арчаад, ганцаараа үлдсэн залгаасыг («—», «·», «-») цэвэрлэнэ:
       «Төлбөр — 20,000,000₮» → «Төлбөр». */
    const bare = part.replace(AMOUNT, "").replace(/\s*[—·-]\s*$/, "").trim();
    /* «барьцаа», «төлбөр» гэх мэт ГАНЦ ЖИЖИГ ҮСГЭЭР эхэлсэн үг нь дүнгийн
       ШОШГО — дүн нь явсан бол ганцаараа утгагүй тул хамт явна. Явдлын нэр
       (Төлбөр, Ачилт, ХҮЧИНГҮЙ, Хэв хашмал ×40) том үсгээр эхэлдэг. */
    if (!bare || (!/\s/.test(bare) && bare[0] === bare[0].toLocaleLowerCase())) return "";
    return bare;
  }).filter(Boolean);

  /* Хамгаалалт: серверийн үг өөрчлөгдөөд дээрх нь ажиллаагүй ч ₮ ГАРАХГҮЙ. */
  return parts.join(" · ").replace(AMOUNT, "").replace(/\s{2,}/g, " ").trim();
}
