import { describe, it, expect } from "vitest";
import { cycleLabel, cycleLastDay, cycleShortLabel } from "./cycle";

/* Отгоогийн циклийн шошго БАГТААМЖТАЙ: «3.15-4.13» гэдэг нь ЯГ 30 хоног —
   4.13 нь циклд ОРНО. Хөдөлгүүр нь хагас нээлттэй [03-15, 04-14) цонхоор
   ажилладаг тул `cycle_end`-ийг ЯГ хэвээр харуулбал төгсгөл нь ҮРГЭЛЖ нэг
   хоногоор хожуу уншигдана — 20 жил тоо уншсан нүд үүнийг «машин нэг хоног
   нэмчихлээ» гэж уншина. ӨГӨГДӨЛ хэвээр, зөвхөн ДҮРСЛЭЛ. */

describe("cycleLastDay", () => {
  it("хагас нээлттэй цонхны сүүлчийн хоног = төгсгөл − 1", () => {
    expect(cycleLastDay("2026-04-14")).toBe("2026-04-13");
  });

  it("сарын хилээр буцна (3.01 → 2.28)", () => {
    expect(cycleLastDay("2026-03-01")).toBe("2026-02-28");
    expect(cycleLastDay("2028-03-01")).toBe("2028-02-29");   // өндөр жил
  });

  it("оны хилээр буцна", () => {
    expect(cycleLastDay("2027-01-01")).toBe("2026-12-31");
  });
});

describe("cycleLabel", () => {
  it("30 хоногийн цикл — түүний уншилтаар", () => {
    expect(cycleLabel("2026-03-15", "2026-04-14")).toBe("2026-03-15 – 2026-04-13");
  });

  it("календарь-сарын цонх бүтэн сараа хэлнэ", () => {
    expect(cycleLabel("2026-04-01", "2026-05-01")).toBe("2026-04-01 – 2026-04-30");
    expect(cycleLabel("2026-01-31", "2026-02-28")).toBe("2026-01-31 – 2026-02-27");
    expect(cycleLabel("2026-12-15", "2027-01-15")).toBe("2026-12-15 – 2027-01-14");
  });

  it("нэг хоногийн цонх нэг л огноо хэлнэ", () => {
    expect(cycleLabel("2026-05-04", "2026-05-05")).toBe("2026-05-04 – 2026-05-04");
  });

  it("хоосон цонхонд урвуу муж хэвлэхгүй (худалдаа, OB)", () => {
    expect(cycleLabel("2026-05-04", "2026-05-04")).toBe("2026-05-04 – 2026-05-04");
  });

  it("огноогүй дуудлагад унахгүй", () => {
    expect(cycleLabel("", "")).toBe("");
    expect(cycleLabel("2026-05-04", "")).toBe("2026-05-04");
  });
});

describe("cycleShortLabel", () => {
  it("гэрээний жагсаалтад зөвхөн сар-өдөр — гэхдээ ижил дүрмээр", () => {
    expect(cycleShortLabel("2026-03-15", "2026-04-14")).toBe("03-15 – 04-13");
  });
});
