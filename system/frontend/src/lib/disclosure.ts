/* Задардаг мөрийн НЭГ дүрэм.
 *
 * Систем дээр задрах мөр ТАВАН өөр дүрээр гарч байв:
 *   · дашбоардын «хугацаа хэтэрсэн» KPI — сум + `aria-expanded` + `aria-controls`
 *     (ЗӨВ загвар, эндээс л хуулагдана)
 *   · гэрээний материалын мөр — зөвхөн сум, самбар нь id-гүй
 *   · тэр материалын 2 дахь мөр — сумгүй мөртлөө задардаг: дарахад ДЭЭД мөрийн
 *     самбар нээгддэг тул хэн ч ойлгохгүй
 *   · /loans мөр — тэмдэг ОГТ байхгүй. Мөрийн хамгийн ил зогсоол нь
 *     зээлдүүлэгчийн нэрэн дээрх ✎ засвар: нүд дарахыг уриалж байгаа зүйл нь
 *     мөрийн үйлдэл БИШ
 *   · /salary бодолтын мөр — мөн тэмдэггүй
 *
 * Эндээс хойш: тэмдэг нь төлөвөө хэлнэ (`ui.tsx` дахь `Chevron`), самбар бүр
 * id-тай (`panelId`), товч нь НЭЭЛТТЭЙ үедээ л түүнийг заана (`disclosureProps`).
 */

/** Самбарын хаяг. Материалын түлхүүр нь `material_id:grade_id` гэх мэт түүхий
 *  утга байдаг тул id-д зохистой болгож цэвэрлэнэ. */
export const panelId = (kind: string, key: string | number): string =>
  `${kind}-panel-${String(key).replace(/[^a-zA-Z0-9_-]/g, "-")}`;

/** `aria-controls` нь БАЙГАА зангилаа заана: хумигдсан үед самбар нь DOM-д огт
 *  байхгүй тул холбоос нь мухардмал болно. Нээлттэй үедээ л заана — хумигдсаныг
 *  `aria-expanded` өөрөө хэлж байгаа. */
export function disclosureProps(open: boolean, id: string):
  { "aria-expanded": boolean; "aria-controls"?: string } {
  return { "aria-expanded": open, ...(open ? { "aria-controls": id } : {}) };
}
