/* ХААЛТТАЙ ХУУДАС — ДЭЛГЭЦ ДЭЭР ХЭЛЭГДЭНЭ, ЭРГЭЛДЭГЧ ДЭЭР БИШ.
 *
 * Үйлдвэрийн даргын цэсэнд «Тайлан» байхгүй. Гэхдээ хаяг нь ажилласаар
 * байсан: хавчуургаа дарсан, хуучин линк дээр товшсон, эсвэл зүгээр л
 * `/reports` гэж бичсэн дарга ХООСОН дэлгэц дээр ЭРГЭЛДЭГЧ ширтэж үлддэг —
 * хуудас нь дата хүлээж байгаа ч сервер 403 буцаасан тул тэр дата ХЭЗЭЭ Ч
 * ирэхгүй. Юу болсныг хэлэх зүйл дэлгэц дээр байхгүй.
 *
 * Одоо хоёр зүйл:
 *   1. Хаалттай хуудсыг НЭЭХГҮЙ — Удирдлагын төв рүү буцаана (тэнд ажил бий);
 *   2. ЯАГААД гэдгийг ЗУРВАС болгож үлдээнэ — «зөвхөн менежер, санхүү».
 * Хоёр дахь нь чухал: «хэн хийх вэ?» гэсэн асуултын хариу дэлгэцэн дээр
 * байхгүй бол хүн утас руу гүйдэг (серверийн 403-ын мөртэй ЯГ нэг журам —
 * `auth.require_roles` мөн «зөвхөн менежер, санхүү» гэж нэрлэдэг).
 *
 * Цэвэр логик: React-гүй, DOM-гүй, чиглүүлэгчгүй — App.tsx түүнийг барина.
 */

/** Ролийн монгол нэр — серверийн `auth.ROLE_MN`-тэй ЯГ ижил үг. */
export const ROLE_MN: Record<string, string> = {
  manager: "менежер",
  finance: "санхүү",
  factory: "үйлдвэрийн дарга",
};

/** Замын хамгаалалт — ЗӨВХӨН эдгээр роль нээж чадна.
 *
 *  Дараалал нь чухал: мөрөнд гарах үг («зөвхөн менежер, санхүү») энэ
 *  жагсаалтын дарааллаар бичигдэнэ.
 *
 *  ⚠ Энэ хүснэгт нь `App.tsx`-ийн `NAV` (цэс) ба серверийн `require_roles`
 *  гуравтайгаа НЭГ үнэн байх ёстой. Цэс нь мөрийг НУУДАГ, энэ нь хаалгыг
 *  ХААДАГ, сервер нь өгөгдлийг хамгаалдаг — гурав нь зөрвөл нэг нь худал. */
const ROUTE_ROLES: [RegExp, readonly string[]][] = [
  /* «МИНИЙ БҮРТГЭЛ» нь бүх рольд — бүтэн бүртгэлээс ӨМНӨ зогсоно (доорх
     `/audit` дүрэм түүнийг залгих байв). Хүн бүр өөрийн үлдээсэн мөрөө
     уншиж чаддаг байх ёстой: дарга тооллого хийгээд үр дүнгээ хардаггүй,
     «суусан уу?» гэж Отгоо руу залгадаг байв. */
  [/^\/audit\/mine(\/|$)/, ["manager", "finance", "factory"]],
  /* ШИНЭ ГЭРЭЭ нь ЗӨВХӨН менежерийнх (сервер: `POST /api/contracts` мөн
     тэгнэ). Санхүүч хаягаа бичээд ороход бөглөж дуустлаа 403 иддэг байв. */
  [/^\/contracts\/new(\/|$)/, ["manager"]],
  /* Санхүүгийн талбай — даргад цэсэнд ч алга, серверт ч 403 (`fin`). */
  [/^\/collections(\/|$)/, ["manager", "finance"]],
  [/^\/loans(\/|$)/, ["manager", "finance"]],
  [/^\/salary(\/|$)/, ["manager", "finance"]],
  [/^\/reports(\/|$)/, ["manager", "finance"]],
  [/^\/analytics(\/|$)/, ["manager", "finance"]],
  /* Зөвхөн эзэн: бүртгэл ба тохиргоо. Тохиргоо нь ЧИМЭЭГҮЙ мөнгө хөдөлгөдөг
     (алдангийн суурь хувь, НДШ) тул сервер ч `require_roles("manager")`. */
  [/^\/audit(\/|$)/, ["manager"]],
  [/^\/settings(\/|$)/, ["manager"]],
  /* БАРТЕР нь ГУРВУУЛАНГИЙНХ — ил бичив. Даргын цэсэнд байдаг (нөөцөд орох
     хөрөнгө нь түүний ажил) ч бичих товч бүр нь менежер+санхүүд; хаалтгүй
     үлдээвэл «жагсаалтад байхгүй = хэн ч болно» гэж уншигдаж, ролийн зураас
     нь цэс дээр л амьдарна. */
  [/^\/barter(\/|$)/, ["manager", "finance", "factory"]],
];

/** Энэ замыг нээж чадах роль. Хаалтгүй зам → `null`. */
export function routeRoles(path: string): readonly string[] | null {
  return ROUTE_ROLES.find(([re]) => re.test(path))?.[1] ?? null;
}

/** Тухайн хүн энэ хуудсыг нээж чадах уу. Роль нь мэдэгдэхгүй бол ХААНА:
 *  нэвтрээгүй хүн хаалттай хуудсыг харах ёсгүй. */
export function canOpen(path: string, role: string | undefined | null): boolean {
  const roles = routeRoles(path);
  if (!roles) return true;
  return !!role && roles.includes(role);
}

/** «менежер, санхүү» — серверийн `auth.roles_text`-тэй нэг үг, нэг дараалал. */
export function rolesText(roles: readonly string[]): string {
  return roles.map((r) => ROLE_MN[r] ?? r).join(", ");
}

/** ЗУРВАСЫН ӨГҮҮЛБЭР. Хаалтгүй зам дээр хоосон — зурвас гарахгүй.
 *
 *  «Энэ хуудас танд хаалттай — зөвхөн менежер, санхүү» */
export function deniedMessage(path: string): string {
  const roles = routeRoles(path);
  return roles ? `Энэ хуудас танд хаалттай — зөвхөн ${rolesText(roles)}` : "";
}
