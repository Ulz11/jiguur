  "/": "Удирдлагын төв", "/contracts": "Гэрээнүүд", "/contracts/new": "Шинэ гэрээ",
  "/clients": "Харилцагч", "/collections": "Авлага цуглуулах", "/warehouse": "Агуулах",
  "/warehouse/stocktake": "Тооллого", "/barter": "Бартер",
