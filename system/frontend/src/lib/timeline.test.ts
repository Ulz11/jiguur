import { describe, it, expect } from "vitest";
import { withoutMoney } from "./timeline";

/* Даргын хуанли нь АЖЛЫН агуулга: «юу болов» нь үлдэж, «хэдэн төгрөг» нь
   хуудасны доод талын «Санхүү» задаргаанд очно (эзний шийдвэр 2026-09 —
   хана биш, ЭМХ ЦЭГЦ). Серверийн бэлэн өгүүлбэрийг ЗАСАЖ байгаа тул
   хэлбэр бүрийг энд нэрлэж барина. */

describe("withoutMoney", () => {
  it("₮-гүй мөрийг ХӨНДӨХГҮЙ", () => {
    expect(withoutMoney("Ачилт — 40ш · №24/03")).toBe("Ачилт — 40ш · №24/03");
    expect(withoutMoney("Гэрээ №24/03 эхлэв")).toBe("Гэрээ №24/03 эхлэв");
  });

  it("ДҮНГИЙН ШОШГО (жижиг үсгээр эхэлсэн ганц үг) хамт явна", () => {
    expect(withoutMoney("Түрээс · барьцаа 500,000₮")).toBe("Түрээс");
    expect(withoutMoney("Хэв хашмал ×40 · төлбөр 500,000₮ · ХҮЧИНГҮЙ (буруу бичив)"))
      .toBe("Хэв хашмал ×40 · ХҮЧИНГҮЙ (буруу бичив)");
  });

  it("ЯВДЛЫН НЭР (том үсгээр эхэлсэн) үлдэж, зөвхөн тоо нь явна", () => {
    expect(withoutMoney("Төлбөр — 20,000,000₮")).toBe("Төлбөр");
    expect(withoutMoney("Төлбөр — 20,000,000₮ · Бэлэн")).toBe("Төлбөр · Бэлэн");
  });

  it("ГАРАХ утганд ₮ ХЭЗЭЭ Ч үлдэхгүй — энэ бол файлын цорын ганц амлалт", () => {
    const samples = [
      "Төлбөр — 20,000,000₮",
      "Түрээс · барьцаа 500,000₮",
      "Худалдаа болгов — 12ш · №26/06 · төлбөр 1,206,500₮",
      "Акт — 5ш · №24/03 · төлбөр 347,500₮ · ХҮЧИНГҮЙ",
      "1,000₮",
      "· 250₮ ·",
    ];
    for (const s of samples) expect(withoutMoney(s), s).not.toContain("₮");
  });

  it("хоосон, null, undefined нь хоосон мөр болно (хуудас унахгүй)", () => {
    expect(withoutMoney("")).toBe("");
    expect(withoutMoney(null)).toBe("");
    expect(withoutMoney(undefined)).toBe("");
  });
});
