/* ХӨДӨЛГӨӨНИЙ ТОЛЬ — нэр ба өнгө нь НЭГ газраас.
 *
 * Нэр нь урьд нь ContractDetail ба MaterialDetail хоёрт ТУСДАА бичигдсэн
 * байв (`t === "ISSUE" ? "Ачилт" : t === "RETURN" ? "Буцаалт" : "Акт"`).
 * Тэр хэлбэрийн хамгийн муу тал нь ЧИМЭЭГҮЙ уналт: шинэ төрөл нэмэгдэхэд
 * хоёулаа «Акт» гэж уншина — Отгоо худалдаа болгосон мөрөө акт гэж хараад
 * итгэлээ алдана (UI-ЗАРЧИМ §3: «нэг ойлголт — нэг үг», «хувирдаг үг»).
 *
 * Сервер талын `billing.MOVEMENT_TYPES`-ийн толин тусгал.
 */
export const MOVEMENT_NAMES: Record<string, string> = {
  ISSUE: "Ачилт",
  RETURN: "Буцаалт",
  WRITEOFF: "Акт",
  // «Худалдаа болгов» — §3 H7-ийн гурав дахь гарц. Гэрээний ТӨРӨЛ «Худалдаа»-
  // гаас ялгарах ёстой тул үйл үгээ авч явна.
  SALE: "Худалдаа болгов",
};

/** Хөдөлгөөний нэр. Танихгүй төрөл нь ӨӨРӨӨРӨӨ гарна — хоосон нүд үлдэхгүй. */
export function mvName(type: string): string {
  return MOVEMENT_NAMES[type] || type;
}

export type MvTone = "brand" | "warn" | "danger" | "violet";

/** Хөдөлгөөний ӨНГӨНИЙ ТОКЕН (UI-ЗАРЧИМ §4 — өнгө нь шатандаа утгатай).
 *
 *  олголт → брэнд (түрээс эхэлж байна) · буцаалт → анхаар · акт → улаан ·
 *  ХУДАЛДАА → violet, яг гэрээний төрөл «Худалдаа»-гийнхтай ижил өнгө.
 *  Өнгө дангаараа утга зөөхгүй тул дэргэд нь ҮРГЭЛЖ `mvName` явна. */
export function mvTone(type: string): MvTone {
  if (type === "RETURN") return "warn";
  if (type === "WRITEOFF") return "danger";
  if (type === "SALE") return "violet";
  return "brand";
}

/* ---------- «Худалдаа болгох» — үржвэр нь ХАРАГДАНА ---------- */
/* «Дутагдуулсан, засварын тооцоо гараар → qty × үнэ автомат. ҮРЖВЭРИЙГ нь
 * харуулбал хурдан» (Чадварын харьцуулалт §4). Отгоогийн арга нь бүх
 * арифметикээ өөрөө дахин бодох явдал: тиймээс дэлгэц үр дүнг биш ҮРЖВЭРИЙГ
 * харуулна («40ш × 58,000₮ = 2,320,000₮»). Функц нь ЦЭВЭР тул тэр тоог
 * гаргасан дүрэм тесттэй. */

export type SaleRow = { qty: number; sale_price: number };

/** Нэг мөрийн худалдааны дүн = тоо × худалдах үнэ (бүхэл төгрөгөөр). */
export function saleRowTotal(r: SaleRow | null | undefined): number {
  return Math.round((r?.qty || 0) * (r?.sale_price || 0));
}

/** Маягтын нийт дүн — мөр бүрийг дугуйлаад нийлүүлнэ (сервертэй ижил журам). */
export function saleTotal(rows: SaleRow[] | null | undefined): number {
  return (rows || []).reduce((s, r) => s + saleRowTotal(r), 0);
}
