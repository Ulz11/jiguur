/** Гэрээний ДУУСАХ ОГНОО — компани түүнийг тавьдаггүй.
 *
 *  Жигүүр Зам гэрээндээ дуусах огноо бичдэггүй: гэрээ хаагдтал явдаг, мөнгө нь
 *  циклүүдийг дагадаг. Тиймээс хоосон огноо нь алдаа биш, ХЭВИЙН байдал —
 *  дэлгэц дээр «None», «null», эсвэл хоосон нүх болж гарах ёсгүй.
 *  Нэг л газар нэрлээд, харагдах бүх газраас энэ функцийг дуудна. */
export function endDateLabel(end: string | null | undefined): string {
  return end && end.trim() ? end : "Хугацаагүй";
}

/** ТООЦООНЫ МӨЧЛӨГ (H3 / R5) — гэрээ 30 хоногоор эсвэл КАЛЕНДАРЬ САРААР явна.
 *
 *  Отгоогийн харилцагчдын цөөнх нь гэрээндээ календарь сараар тохирсон: цикл
 *  нь '4.01–4.30', дараа нь '5.01–5.31' болж, 31 хоногтой сар ×31/30 ИЛҮҮ
 *  нэхэгддэг. Энэ бол алдаа биш — гарын үсэгтэй нөхцөл.
 *
 *  Хоёр горимын нэр НЭГ эх сурвалжаас гарна: wizard-ийн сегмент, гэрээний
 *  дэлгэрэнгүйн InlineEdit, баталгаажуулах хуудас гуравт өөр өөр үг бичигдвэл
 *  Отгоо «хоёр өөр тохиргоо байна уу» гэж эргэлзэнэ. */
export const CYCLE_MODES: [string, string][] = [
  ["days", "30 хоног"],
  ["month", "Календарь сар"],
];

const CYCLE_MODE_MAP = new Map(CYCLE_MODES);

export function cycleModeLabel(mode: string | null | undefined): string {
  return CYCLE_MODE_MAP.get((mode || "").trim()) ?? CYCLE_MODES[0][1];
}

/** ЖАГСААЛТЫН мөрөнд гарах тэмдэг — анхны горимд ХООСОН (мөр гарахгүй).
 *
 *  Гэрээнүүдийн 95% нь «30 хоног» тул түүнийг ч тэмдэглэвэл жагсаалт бүхэлдээ
 *  тэмдэгтэй болж, ЯЛГАА нь алга болно. Отгоо дэлгэц дээр болж буйг
 *  анзаардаггүй — ялгарах зүйл ЦӨӨН байх тусам харагдана. Тиймээс тэмдэг нь
 *  зөвхөн ОНЦГОЙ горимд, толины ижил үгээр (`cycleModeLabel`) зогсоно. */
export function cycleModeBadge(mode: string | null | undefined): string {
  return (mode || "").trim() === "month" ? cycleModeLabel("month") : "";
}

/** Календарь горимын НЭГ мөрийн тайлбар — гэрээний эхлэх огнооны ӨДРӨӨР.
 *
 *  Зангилаа нь эхлэх огнооны өдөр; 29–31-нд эхэлсэн гэрээнд тэр өдөр 2-р сард
 *  байхгүй тул сарын сүүлчийн өдөр рүү хумигдана (дараа сар нь зангилаандаа
 *  ЭРГЭЖ ОЧНО). Хумилтыг НУУВАЛ 2-р сарын нэхэмжлэл гэнэт «буруу» өдөр
 *  дээр гарч ирнэ — тиймээс сонгохын өмнө хэлнэ. */
export function cycleModeHint(startDate: string | null | undefined): string {
  const day = Number((startDate || "").trim().slice(8, 10));
  if (!day || Number.isNaN(day)) {
    return "Эхлэх огнооны өдөр бүрд шинэ цикл — 31 хоногтой сар 31 хоногоор нэхэгдэнэ";
  }
  const clamp = day > 28 ? " (богино сард сарын сүүлчийн өдөр)" : "";
  return `Сар бүрийн ${day}-нд шинэ цикл${clamp} — 31 хоногтой сар 31 хоногоор нэхэгдэнэ`;
}

/* ══════════════ ШИНЭ ГЭРЭЭНИЙ ХАТУУ ЗОГСООЛ (2026-09) ══════════════
 *
 * Wizard-ийн 2-р алхам нь 34ш нөөцтэй материалаас 120ш олгох мөрийг улаанаар
 * тэмдэглээд «Цааш» товчийг НЭЭЛТТЭЙ үлдээдэг байв; 0₮ тариф ч чөлөөтэй
 * өнгөрдөг. Тэр хоёр гэрээ ТӨРСӨН ЦАГААСАА буруу тоо үйлдвэрлэнэ (нөөц
 * сөрөг, өдрийн дүн 0) бөгөөд Отгоо тэр алдааг сар хагасын дараа авлага
 * зөрөхөөр нь олно.
 *
 * ӨНГӨ ДАНГААРАА УТГА ЗӨӨХГҮЙ (UI-ЗАРЧИМ §4): улаан хүрээ нь «болохгүй» гэж
 * ХЭЛДЭГГҮЙ — үг л хэлнэ. Тиймээс зогсоол бүр өөрийн ӨГҮҮЛБЭРТЭЙ, тэр
 * өгүүлбэр нь ХОЁР тоог (юу байна / юу гуйж байна) нэрлэнэ.
 */

/** «Агуулахад 34ш байна — 120ш олгох боломжгүй». Зогсоолгүй бол хоосон.
 *
 *  Нөөц нь мэдэгдэхгүй (сервер илгээгээгүй) бол ХОРИХГҮЙ: таамгаар зам хаах
 *  нь буруу тоо оруулахаас дор — Отгоо гэрээгээ огт үүсгэж чадахгүй болно. */
export function stockStop(qty: number, onHand: number | null | undefined): string {
  if (onHand == null || !Number.isFinite(onHand)) return "";
  if (!(qty > onHand)) return "";
  return `Агуулахад ${fmt(onHand)}ш байна — ${fmt(qty)}ш олгох боломжгүй`;
}

/** «Тариф 0₮ — үнийг тогтооно уу (Тохиргоо → Материалын каталог)».
 *
 *  Нэр нь БАГАНЫНХАА үгээр явна (түрээс → «Тариф», худалдаа → «Нэгж үнэ») —
 *  нэг ойлголт нэг үг (§3). Мөр нь ЗАСАХ ГАЗРЫГ зааж өгнө: «үнэ алга» гэж
 *  хэлээд хаана тавихыг хэлэхгүй бол Отгоо wizard-аа орхиж явна. */
export function rateStop(rate: number, type: "rent" | "sale"): string {
  if (rate > 0) return "";
  const name = type === "rent" ? "Тариф" : "Нэгж үнэ";
  return `${name} ${fmt(rate)}₮ — үнийг тогтооно уу (Тохиргоо → Материалын каталог)`;
}

/* ══════════════ ГЭРЭЭ СУНГАХ ══════════════
 *
 * Цонх нь ӨНӨӨДРИЙГ санал болгодог байв: «сунгах» гэж нээгээд ижил (эсвэл
 * өмнөх) огноо тавихад гэрээ сунгагдахын оронд БОГИНОСНО. Санал нь дуусах
 * огноогоо 30 хоногоор урагшлуулсан тоо — тэр бол түүний хамгийн түгээмэл
 * сунгалт; өнгөрсөн огноо нь «сунгалт» гэсэн үгтэй зөрчилддөг тул хориотой.
 */

/** Сунгалтын анхны утга — дуусах огноо (эсвэл өнөөдөр) + 30 хоног. */
export function extendDefault(endDate: string | null | undefined,
                              todayIsoStr: string): string {
  const end = (endDate || "").trim();
  const base = end && end >= todayIsoStr ? end : todayIsoStr;
  return addDays(base, EXTEND_DAYS);
}

/** Өнгөрсөн рүү «сунгах» гэж байхгүй — огноог нэрлээд татгалзана. */
export function extendStop(date: string | null | undefined, todayIsoStr: string): string {
  const d = (date || "").trim();
  if (!d || d >= todayIsoStr) return "";
  return `${d} нь өнөөдрөөс өмнө — сунгах огноо хойшоо байна`;
}

/** Түүний хамгийн түгээмэл сунгалт — нэг цикл. */
export const EXTEND_DAYS = 30;
