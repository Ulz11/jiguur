import { describe, it, expect } from "vitest";
import { addDays, daysBetween, dueLabel, todayIso } from "./schedule";

// «2026-09-14» гэсэн огноо ганцаараа «удахгүй юу, дараа сар уу» гэдгийг
// хэлдэггүй. Хүлээгдэж буй төлбөрийн жагсаалт дээр Отгоо огноог биш ХОНОГИЙГ
// хардаг — тиймээс хөрвүүлэлт нэг цэвэр дүрэмтэй байна.

describe("daysBetween", () => {
  it("хоёр огнооны хоорондох хоногийг тоолно", () => {
    expect(daysBetween("2026-08-29", "2026-09-14")).toBe(16);
    expect(daysBetween("2026-09-14", "2026-08-29")).toBe(-16);
    expect(daysBetween("2026-08-29", "2026-08-29")).toBe(0);
  });

  it("сар, жилийн зааг дээр ч зөв (2026 нь өндөр жил биш)", () => {
    expect(daysBetween("2026-02-28", "2026-03-01")).toBe(1);
    expect(daysBetween("2026-12-31", "2027-01-01")).toBe(1);
  });

  it("зуны цагийн шилжилт хоногийг 0.96 болгож бөөрөнхийлүүлэхгүй", () => {
    // Хэрэв UTC-гээр уншвал зарим бүсэд 23 эсвэл 25 цаг гарч хоног алдагдана
    expect(daysBetween("2026-03-28", "2026-03-30")).toBe(2);
    expect(daysBetween("2026-10-24", "2026-10-26")).toBe(2);
  });
});

describe("dueLabel", () => {
  it("өнөөдөр, маргааш гэдгийг тоогоор биш үгээр хэлнэ", () => {
    expect(dueLabel("2026-08-29", "2026-08-29")).toBe("өнөөдөр");
    expect(dueLabel("2026-08-30", "2026-08-29")).toBe("маргааш");
  });

  it("ирээдүйн огноог хэдэн хоногийн дараа болохоор нь хэлнэ", () => {
    expect(dueLabel("2026-09-14", "2026-08-29")).toBe("16 хоногийн дараа");
  });

  it("өнгөрсөн огноо хэтэрсэн гэж уншигдана (жагсаалт хоцорч сэргэсэн ч)", () => {
    expect(dueLabel("2026-08-27", "2026-08-29")).toBe("2 хоног хэтэрсэн");
  });
});

describe("todayIso", () => {
  it("ЛОКАЛ огноог өгнө — toISOString() нь UTC тул шөнө нэг хоног хазайдаг", () => {
    expect(todayIso(new Date(2026, 7, 29, 23, 30))).toBe("2026-08-29");
    expect(todayIso(new Date(2026, 0, 1, 0, 15))).toBe("2026-01-01");
  });
});

/* `addDays` — «дуусах огноо + 30 хоног» гэсэн САНАЛЫГ бодох ганц зам.
   `new Date(iso)` нь UTC-гээр уншдаг тул UTC+8 дээр нэг хоногоор хазайдаг:
   энэ функц нь `daysBetween`-тэй ижил ЛОКАЛ хуанлигаар явна. */

describe("addDays", () => {
  it("хоног нэмнэ — сар, жилийн зааг дамжина", () => {
    expect(addDays("2026-09-05", 30)).toBe("2026-10-05");
    expect(addDays("2026-12-20", 30)).toBe("2027-01-19");
    expect(addDays("2026-01-31", 1)).toBe("2026-02-01");
  });

  it("хасах чиглэлд ч ажиллана", () => {
    expect(addDays("2026-09-05", -5)).toBe("2026-08-31");
  });

  it("нэмсэн хоног нь `daysBetween`-ээр буцаж уншигдана", () => {
    expect(daysBetween("2026-09-05", addDays("2026-09-05", 30))).toBe(30);
  });
});
