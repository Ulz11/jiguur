"""Нэрийн ЭРЭМБЭ — диалектаас ҮЛ ХАМААРАХ.

SQLite-ийн `ORDER BY name` нь default `BINARY` эрэмбэ: UTF-8 байтаар, өөрөөр
хэлбэл Unicode кодын дугаараар. Postgres нь сангийн `LC_COLLATE`-ыг дагана —
ихэвчлэн `en_US.UTF-8`, тэр нь кирилл үсгийг ӨӨР дарааллаар тавина (мөн
`libc` ↔ `ICU`, Postgres-ийн хувилбар хооронд ч ялгаатай).

Отгоо эгчийн хувьд «Ө» үсэг жагсаалтын аль хэсэгт байх нь ач холбогдолгүй —
харин ТУРШИЛТЫН ОРЧИН ба БОДИТ ОРЧИН хоёр ӨӨР дараалал үзүүлэх нь асуудал:
«миний харилцагч жагсаалтаас алга болов» гэсэн дуудлага болно. Тиймээс
эрэмбийг САНД ҮЛДЭЭХГҮЙ, Python-д хийнэ: `str` харьцуулалт нь кодын
дугаараар явдаг тул хоёр диалект дээр ЯГ ижил, өнөөдрийн SQLite-тай ч ижил.
"""


def by_name(rows, attr: str = "name"):
    """Мөрүүдийг нэрээр нь (кодын дугаараар) эрэмбэлнэ."""
    return sorted(rows, key=lambda r: getattr(r, attr) or "")


def by_fields(rows, *attrs: str):
    """Хэд хэдэн текст талбараар — ж. (категори, нэр) эсвэл (төрөл, нэр)."""
    return sorted(rows, key=lambda r: tuple(getattr(r, a) or "" for a in attrs))
